public class Operations {
    public static int sum(int a, int b) {
        return a+b;
    }

    public static int minus(int a, int b) {
        return a-b;
    }

    public static int umnozhenie(int a, int b) {
        return a*b;
    }

    public static int delenie(int a, int b) {
        return a/b;
    }
}
